"""Diagnostics of the FX: why an effect is not visible.

The audit of the operational plan asks for a report that distinguishes the
real causes of an invisible effect:

``MISSING_ATTRIBUTE``
    the material reads an attribute that nobody writes (the trails had no
    ``energy``: the shader read nothing and the curve stayed dark);
``FUTURE`` / ``ENDED``
    the event is out of its time window;
``OFF_CAMERA`` / ``OFF_CLIPPING``
    the event is outside the frame or outside the clipping range;
``DISABLED``
    the system or the event does not take part in the render;
``NON_EMISSIVE``
    the material has no emission: the geometry is there but it is dark;
``HIDDEN``
    the objects are hidden in the view layer or in the render;
``NO_GEOMETRY``
    the event has no object at all.

The module never writes anything: it only reads the scene.
"""

import math

import bpy
from bpy_extras.object_utils import world_to_camera_view

from . import fx as fx_module

#: The states of an event, in the order of the diagnostic.
STATES = (
    "OK",
    "UNKNOWN",
    "NO_GEOMETRY",
    "DISABLED",
    "MISSING_ATTRIBUTE",
    "NON_EMISSIVE",
    "HIDDEN",
    "FUTURE",
    "ENDED",
    "OFF_CAMERA",
    "OFF_CLIPPING",
)

#: The attributes the material of the FX reads.
MATERIAL_ATTRIBUTES = ("energy",)


def runtime_info(scene):
    """The state of the runtime: the version, the backend and the schemas."""
    from . import fx_nodes
    from .properties import FX_SCHEMA
    import sys

    module = sys.modules.get(__package__)
    version = tuple(module.bl_info["version"]) if module else (0, 0, 0)
    settings = getattr(scene, "ald", None)
    groups = {}
    for name in (fx_nodes.GROUP_NAME, fx_nodes.TRAIL_GROUP_NAME):
        group = bpy.data.node_groups.get(name)
        groups[name] = int(group.get("ald_schema", 0)) if group else 0
    camera = scene.camera
    camera_data = camera.data if camera is not None else None
    return {
        "version": ".".join(str(part) for part in version),
        "backend": getattr(settings, "fx_backend", "OFF") if settings else "OFF",
        "data_schema": int(getattr(settings, "fx_schema", 0)) if settings else 0,
        "data_schema_current": FX_SCHEMA,
        "group_schema": groups,
        "group_schema_current": fx_nodes.SCHEMA,
        "engine": scene.render.engine,
        "fps": round(fx_module._fps(scene), 4),
        "frame": scene.frame_current,
        "resolution": (scene.render.resolution_x, scene.render.resolution_y),
        "view_transform": scene.view_settings.view_transform,
        "exposure": round(float(scene.view_settings.exposure), 4),
        "units": (scene.unit_settings.system,
                  scene.unit_settings.scale_length),
        "camera": camera.name if camera is not None else None,
        "camera_lens": round(float(camera_data.lens), 2)
        if camera_data is not None else None,
        "film_transparent": bool(scene.render.film_transparent),
        "view_layers": [layer.name for layer in scene.view_layers],
    }


def _objects_of_event(scene, uid):
    """The objects generated by an event."""
    owner = fx_module._scene_id(scene)
    found = []
    for coll in bpy.data.collections:
        if coll.get(fx_module.OWNER_KEY) != owner:
            continue
        for obj in coll.objects:
            if not obj.get("ald_fx"):
                continue
            if obj.get("ald_fx_event") == uid:
                found.append(obj)
    return found


def _material_states(objects):
    """The attributes the materials read and the emission of the objects."""
    missing = []
    dark = []
    for obj in objects:
        data = obj.data
        material = None
        if data is not None and hasattr(data, "materials") and data.materials:
            material = data.materials[0]
        if material is None or not material.use_nodes:
            continue
        tree = material.node_tree
        for node in tree.nodes:
            if node.bl_idname != "ShaderNodeAttribute":
                continue
            name = node.attribute_name
            if name not in MATERIAL_ATTRIBUTES:
                continue
            # The attribute is written by the node group or by the writer.
            if obj.type == "MESH" and data.attributes.get(name) is not None:
                continue
            if any(modifier.type == "NODES" for modifier in obj.modifiers):
                continue
            missing.append((obj.name, name))
        strength = None
        for node in tree.nodes:
            if node.bl_idname != "ShaderNodeBsdfPrincipled":
                continue
            if "Emission Strength" in node.inputs:
                strength = node.inputs["Emission Strength"]
                if strength.is_linked:
                    continue
                if float(strength.default_value) <= 0.0:
                    dark.append(obj.name)
        if strength is None and "Emission" in material.node_tree.nodes:
            pass
    return missing, dark


def _head_position(scene, objects):
    """The world position of the first alive particle of the event."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    for obj in objects:
        if obj.type != "MESH":
            continue
        if obj.get("ald_fx_role") == "launcher":
            continue
        try:
            from . import fx_nodes
            centers = fx_nodes.realized_centers(obj, depsgraph)
            if centers:
                return centers[0]
        except Exception:
            pass
        evaluated = obj.evaluated_get(depsgraph)
        try:
            mesh = evaluated.to_mesh()
        except Exception:
            mesh = None
        if mesh is not None and len(mesh.vertices):
            total = Vector((0.0, 0.0, 0.0))
            for vertex in mesh.vertices:
                total += vertex.co
            centre = total / len(mesh.vertices)
            evaluated.to_mesh_clear()
            return centre
        if mesh is not None:
            evaluated.to_mesh_clear()
    return None


def _projection(scene, position):
    """The position in the frame: (x, y, depth) in normalized coordinates."""
    camera = scene.camera
    if camera is None or position is None:
        return None
    try:
        return world_to_camera_view(scene, camera, position)
    except Exception:
        return None


def event_state(scene, system, event):
    """The state of one event: the reason why it is not visible."""
    settings = getattr(scene, "ald", None)
    state = {
        "uid": event.uid,
        "kind": event.kind,
        "state": "UNKNOWN",
        "reason": "",
        "objects": 0,
        "local_time": 0.0,
        "position": None,
        "projected": None,
    }
    if settings is None:
        state["state"] = "NO_GEOMETRY"
        state["reason"] = "the settings are not registered"
        return state
    if not system.enabled or not event.enabled:
        state["state"] = "DISABLED"
        state["reason"] = "the system or the event is disabled"
        return state
    objects = _objects_of_event(scene, event.uid)
    state["objects"] = len(objects)
    if not objects:
        state["state"] = "NO_GEOMETRY"
        state["reason"] = "the event has no object: it was never compiled"
        return state
    missing, dark = _material_states(objects)
    if missing:
        state["state"] = "MISSING_ATTRIBUTE"
        state["reason"] = "the material reads %s and nobody writes it" % \
            ", ".join(sorted({name for _obj, name in missing}))
        return state
    if dark:
        state["state"] = "NON_EMISSIVE"
        state["reason"] = "the emission of the material is zero"
        return state
    hidden = [obj.name for obj in objects
              if obj.hide_render or obj.hide_viewport]
    if hidden:
        state["state"] = "HIDDEN"
        state["reason"] = "the objects are hidden: %s" % ", ".join(hidden[:3])
        return state
    # Read-only part: timing only. Position/projection requires evaluating the
    # depsgraph (which may modify shared Geometry Nodes groups) and must be
    # done by an explicit operator, not during panel draw.
    time = fx_module.system_time(scene, system)
    local = time - float(event.birth)
    state["local_time"] = round(local, 4)
    life = float(event.life) if float(event.life) > 0.0 else 1.0
    if local < 0.0:
        state["state"] = "FUTURE"
        state["reason"] = "the event starts in %.3f s" % (-local)
        return state
    if local > life:
        state["state"] = "ENDED"
        state["reason"] = "the event ended %.3f s ago" % (local - life)
        return state
    state["position"] = None
    state["projected"] = None
    # The read-only pass cannot prove that the event is visible: the
    # projection needs the depsgraph. Report UNKNOWN, never OK, until the
    # explicit Diagnose FX operator has evaluated it.
    state["state"] = "UNKNOWN"
    state["reason"] = ("the timing is valid; run Diagnose FX to verify the "
                       "projection and the occlusion")
    return state


def diagnose_event(scene, system, event):
    """Full diagnostic of one event, including position/projection.

    This evaluates the depsgraph and may temporarily modify shared Geometry
    Nodes groups (via realized_centers). Call only from an explicit operator,
    never during panel draw.
    """
    state = event_state(scene, system, event)
    # If the event passed all read-only checks, go deeper: evaluate position.
    if state["state"] == "UNKNOWN":
        objects = _objects_of_event(scene, event.uid)
        position = _head_position(scene, objects)
        if position is not None:
            state["position"] = [round(value, 3) for value in position]
            projected = _projection(scene, position)
            if projected is not None:
                state["projected"] = [round(float(projected.x), 3),
                                      round(float(projected.y), 3),
                                      round(float(projected.z), 3)]
                if projected.z <= 0.0:
                    state["state"] = "OFF_CLIPPING"
                    state["reason"] = "the event is behind the camera"
                elif not (0.0 <= projected.x <= 1.0
                          and 0.0 <= projected.y <= 1.0):
                    state["state"] = "OFF_CAMERA"
                    state["reason"] = "the event is outside the frame"
                else:
                    state["state"] = "OK"
                    state["reason"] = ""
        else:
            state["reason"] = "no head position could be evaluated"
    return state


def diagnose_scene(scene):
    """Full diagnostic of all events in the scene, including position.

    Intended to be called by an explicit operator, not during panel draw.
    Returns a JSON-serializable dict.
    """
    settings = getattr(scene, "ald", None)
    data = {"runtime": runtime_info(scene), "systems": []}
    if settings is None:
        return data
    for system in settings.fx_systems:
        runtime = fx_module.runtime_by_uid(scene, system.uid)
        entry = {
            "uid": system.uid,
            "kind": system.kind,
            "enabled": bool(system.enabled),
            "timing_mode": system.timing_mode,
            "origin_frame": int(system.origin_frame),
            "origin_time": round(float(system.origin_time), 4),
            "local_time": round(fx_module.system_time(scene, system), 4),
            "compiled": runtime is not None,
            "backend": "Geometry Nodes" if (runtime or {}).get("gn")
            else ("Python" if runtime else "none"),
            "events": [],
        }
        for event in system.events:
            entry["events"].append(diagnose_event(scene, system, event))
        data["systems"].append(entry)
    return data


def report(scene):
    """The complete report of the FX of a scene."""
    settings = getattr(scene, "ald", None)
    data = {"runtime": runtime_info(scene), "systems": []}
    if settings is None:
        return data
    for system in settings.fx_systems:
        runtime = fx_module.runtime_by_uid(scene, system.uid)
        entry = {
            "uid": system.uid,
            "kind": system.kind,
            "enabled": bool(system.enabled),
            "timing_mode": system.timing_mode,
            "origin_frame": int(system.origin_frame),
            "origin_time": round(float(system.origin_time), 4),
            "local_time": round(fx_module.system_time(scene, system), 4),
            "compiled": runtime is not None,
            "backend": "Geometry Nodes" if (runtime or {}).get("gn")
            else ("Python" if runtime else "none"),
            "events": [],
        }
        for event in system.events:
            entry["events"].append(event_state(scene, system, event))
        data["systems"].append(entry)
    return data


def summary(scene):
    """A short summary of the report: the states and their counts."""
    data = report(scene)
    counts = {}
    for system in data["systems"]:
        for event in system["events"]:
            counts[event["state"]] = counts.get(event["state"], 0) + 1
    return counts


def format_report(scene):
    """The report as text, for the console and for the panel."""
    data = report(scene)
    lines = []
    runtime = data["runtime"]
    lines.append("Anime Look Director %s | backend %s | data %d | groups %s"
                 % (runtime["version"], runtime["backend"],
                    runtime["data_schema"],
                    ",".join(str(value) for value in
                             runtime["group_schema"].values())))
    lines.append("%s | %s | %d fps | frame %d | %s"
                 % (runtime["engine"], runtime["view_transform"],
                    runtime["fps"], runtime["frame"],
                    ", ".join(runtime["view_layers"])))
    for system in data["systems"]:
        lines.append("system %s %s (%s) t=%.3f s"
                     % (system["uid"][:8], system["kind"],
                        system["backend"], system["local_time"]))
        for event in system["events"]:
            lines.append("  event %s %-8s %-17s %s"
                         % (event["uid"][:8], event["kind"], event["state"],
                            event["reason"]))
    return "\n".join(lines)
